/**
 * Id, виведені з природного ключа (MER-57).
 *
 * ## Навіщо
 *
 * LWW розсуджує зміни наявного рядка, але не дві незалежні спроби його
 * СТВОРИТИ. Там, де в схемі стоїть частковий унікальний індекс, друга вставка з
 * іншого пристрою відкидається сервером (`23505`), конектор вважає код класу 23
 * фатальним — і **відкидає зміну**. Для користувача дія просто скасовується
 * сама: локальний рядок зникає на наступному чекпоінті.
 *
 * Ліки: обидва пристрої рахують ОДИН id із того самого природного ключа.
 * Вивантаження тоді стає upsert того самого рядка (`applyCrudEntry`, PUT), і
 * далі роботу робить звичайний LWW — рівно так, як для будь-якої іншої зміни.
 *
 * ## Чому тут, а не поруч із записом
 *
 * Ті самі id мають рахувати й веб, і Capacitor, і міграція V1 (MER-48). Один
 * модуль без залежностей від БД — єдине місце, де це можна тримати чесно.
 *
 * ## Правила
 *
 * - **Простір імен не змінюється НІКОЛИ** після першого запису: інакше та сама
 *   позначка на іншій версії застосунку дасть інший id — і повернеться рівно та
 *   колізія, від якої цей модуль рятує.
 * - **Ім'я складається з природного ключа**, тобто з тих самих колонок, що й у
 *   частковому унікальному індексі. Розійтися вони не мають права.
 * - **Виведений id — лише для ВСТАВКИ.** Наявний рядок шукається за природним
 *   ключем, а не за виведеним id: смак могли поставити ще до цієї зміни, і тоді
 *   в базі лежить рядок із випадковим id (див. `setMealPref`).
 */

import { v5 as uuidv5 } from 'uuid'

/**
 * Простір імен Meridian для UUIDv5. Фіксована константа: саме вона робить
 * виведення відтворюваним між запусками й пристроями.
 */
export const MERIDIAN_NAMESPACE = '08f391fa-7b00-47c8-9fc6-61847964d799'

/**
 * Розділювач частин імені — NUL. Він не може трапитись усередині жодного зі
 * складників, тож розібрати ім'я на інші частини неможливо: `('a', 'bc')` і
 * `('ab', 'c')` дають різні id, а без розділювача дали б однаковий.
 *
 * Записаний екранованою послідовністю навмисно: справжній NUL у `.ts` робить
 * файл двійковим для частини інструментів (ripgrep такий файл просто пропускає).
 */
const SEP = '\u0000'

/**
 * UUIDv5 з імені, зібраного зі складників природного ключа.
 *
 * Перший складник у кожному виклику різний за формою — назва таблиці або id
 * сім'ї, — тож імена різних різновидів не можуть збігтися між собою.
 *
 * Експортується для `shopping.ts`: відбиток списку — не id рядка, але
 * складається за тим самим правилом, і другої копії розділювача в коді бути не
 * повинно. У `index.ts` не виноситься — це внутрішня деталь ядра.
 */
export function derive(parts: ReadonlyArray<string>): string {
  // Порядок аргументів саме такий: спершу ім'я, потім простір імен.
  return uuidv5(parts.join(SEP), MERIDIAN_NAMESPACE)
}

/* ==========================================================================
 * Міграція V1 → V2 (MER-48)
 * ======================================================================== */

/** Різновиди рядків, id яких виводяться з id запису V1. */
export type IdKind = 'meal' | 'recipe' | 'profile'

/**
 * Вивести id рядка V2 з id запису V1.
 *
 * У V1 `id` — довільний рядок (`generateId`), у V2 колонка має тип `uuid`, тож
 * прямо перенести не вийде. Виведення (а не генерація) дає дві речі:
 *  - імпорт **ідемпотентний**: повторний запуск оновлює ті самі рядки, а не
 *    подвоює пул;
 *  - посилання всередині даних лишаються цілі — смаки, `mealIds` профілю й
 *    `sharedPlanWith` перераховуються в ті самі нові значення.
 *
 * **`familyId` у складі імені — не прикраса.** Профіль за замовчуванням у V1
 * має буквальний id `default` (`ProfileStore.DEFAULT_ID`), тобто однаковий у
 * КОЖНОГО користувача. Без сім'ї в імені дві родини на одному self-host вивели
 * б той самий UUID і зіткнулися б на первинному ключі.
 */
export function derivedId(
  familyId: string,
  kind: IdKind,
  v1Id: string,
): string {
  return derive([familyId, kind, v1Id])
}

/* ==========================================================================
 * Рядки, які захищені частковим унікальним індексом (MER-57)
 * ======================================================================== */

/**
 * Id смаку страви (MER-18).
 *
 * Природний ключ — сама страва: індекс `meal_pref_meal_id_key` стоїть на
 * `(meal_id) WHERE deleted_at IS NULL`. Сім'ї в імені немає навмисно — її вже
 * визначає `meal_id`, який унікальний на весь self-host.
 *
 * Сценарій, заради якого це робиться: двоє позначають ту саму страву ♥/🚫 —
 * офлайн або просто в межах вікна синхронізації.
 */
export function mealPrefId(mealId: string): string {
  return derive(['meal_pref', mealId])
}

/**
 * Id позначки «куплено» в списку покупок (MER-16).
 *
 * Природний ключ — усі три колонки індексу `shopping_check_item_key_key`:
 * `(family_id, item_key, fingerprint)`. Сім'я тут потрібна, на відміну від
 * смаку: `item_key` — вільний рядок («q:помідор|шт»), і в двох сім'ях він
 * збігається легко.
 *
 * Сценарій — той, заради якого взагалі робився sync: двоє в магазині
 * відмічають ту саму позицію. Позначку створює `setShoppingCheck`
 * (`apps/web/src/lib/data/mutations.ts`, MER-62) саме з цим id; сам відбиток
 * рахує `planFingerprint` у `shopping.ts`.
 */
export function shoppingCheckId(
  familyId: string,
  itemKey: string,
  fingerprint: string,
): string {
  return derive(['shopping_check', familyId, itemKey, fingerprint])
}

/**
 * Id слота плану — одного прийому їжі одного дня (MER-66).
 *
 * Природний ключ — усі три колонки індексу `plan_slot_profile_date_slot_key`:
 * `(profile_id, date, slot)`. Сім'ю вже визначає `profile_id`. `week_plan_id`
 * в імені немає навмисно: слот — це клітинка календаря, і перегенерація тижня
 * ПЕРЕПИСУЄ ту саму клітинку, а не заводить нову (MER-49) — саме тому LWW
 * працює на рівні слота.
 *
 * Сценарій: двоє офлайн генерують тиждень на ті самі дати вперше. Читання
 * перед записом тут не рятує — жоден іще не має рядка, обидва вставляють, і
 * друга вставка гине на індексі (MER-57, той самий клас).
 *
 * `date` — рядок `YYYY-MM-DD`, як він лежить у колонці `date` і як його дає
 * `planSlots`; `slot` — значення enum `meal_type` («breakfast» тощо).
 */
export function planSlotId(
  profileId: string,
  date: string,
  slot: string,
): string {
  return derive(['plan_slot', profileId, date, slot])
}

/**
 * Id рецепта страви (заведено в MER-66, споживач — сторінка рецепта, MER-63).
 *
 * Природний ключ — сама страва: індекс `recipe_meal_id_key` стоїть на
 * `(meal_id)`. На відміну від решти, індекс НЕ частковий: м'яко видалений
 * рецепт теж тримає ключ. Тому для рецепта пошук за природним ключем перед
 * записом обов'язковий подвійно: будь-який наявний рядок — живий, м'яко
 * видалений, з випадковим id чи з id міграції V1 (`derivedId(family,
 * 'recipe', v1Id)`, MER-48) — блокує вставку, і його треба оновлювати, а не
 * вставляти поруч. Виведений id — лише коли рядка немає зовсім.
 */
export function recipeId(mealId: string): string {
  return derive(['recipe', mealId])
}
