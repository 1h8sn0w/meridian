/**
 * Список покупок із тижня (MER-16 → MER-62) — збірка позицій і їхні ключі.
 *
 * Модуль **нічого не вигадує**. Правило провенансу (AGENTS.md) тут читається
 * буквально, і всі три його прояви — рішення, а не дрібниці реалізації:
 *
 *  - **кількість — лише там, де вона є в даних страви.** Сумуються записи з
 *    однаковою назвою ТА однаковою одиницею («г» до «г», «шт» до «шт»): 100 г
 *    плюс 2 шт — це не «102 чогось», і зводити їх нема за яким курсом;
 *  - **інгредієнт без кількості лишається без кількості.** Такі позиції йдуть
 *    окремим переліком, самими назвами: «типових» грамовок застосунок не
 *    проставляє. Одиниця без числа («до смаку») — теж сюди;
 *  - **категорія — за словником точних назв.** Невідома назва чесно падає в
 *    «Інше». Збіг за підрядком («сир» усередині «сирок») вгадував би категорію
 *    там, де її в даних немає.
 *
 * Сам список ніде не зберігається — він щоразу збирається з інгредієнтів страв
 * поточних планів. Зберігаються лише позначки «куплено» (`shopping_check`), і
 * ключ позиції з `aggregate` — це і є їхній `item_key`.
 */

