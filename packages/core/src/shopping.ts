/** Один план охоплення: чий він і яким рядком `week_plan` представлений. */
export type PlanStamp = { ownerId: string; planId: string }

/**
 * Відбиток планів — «те саме походження в магазин», під яким зроблено позначки.
 *
 * Він розв'язує рівно одну задачу: **перегенерація тижня — це новий похід у
 * магазин**, і вчорашні «куплено» до нового списку відношення не мають. У V1
 * відбиток лежав поруч зі списком і його зміна СТИРАЛА позначки; тут він стоїть
 * на кожному рядку `shopping_check`, тож скидання — це фільтр, а не руйнівний
 * запис (рішення MER-55), і гонки «хто перший стер» немає.
 *
 * **Складається з id рядків `week_plan`, а не з `generated_at`.** Дві причини, і
 * обидві — про синхронізацію:
 *
 *  - `generated_at` лежить у локальному SQLite ТЕКСТОМ, і форма тексту залежить
 *    від того, хто записав рядок: пристрій пише ISO з «T», реплікація віддає
 *    серверну форму з пробілом (те саме розрізнення описує `LATEST_PLAN_ORDER`
 *    у `queries.ts`). Той самий план дав би на двох пристроях РІЗНИЙ відбиток —
 *    і позначка одного просто не потрапляла б у список іншого. Це рівно те, що
 *    задача вимагає не зламати;
 *  - обрізати текст до секунд, щоб форми зійшлися, теж не можна: дві
 *    перегенерації в ту саму секунду дали б однаковий відбиток, і старі
 *    позначки перетекли б у новий список.
 *
 * Id рядка плану вільний від обох: `saveWeek` заводить на кожну генерацію новий
 * рядок, а ручна заміна страви (MER-12) плану не перестворює — тож заміна
 * позначки переживає, як і у V1.
 *
 * **Охоплення (`scope`) у відбиток не входить.** Воно — фільтр показу на
 * пристрої (рішення MER-55), а позначки спільні для сім'ї: два телефони з
 * різним охопленням мусять бачити позначки одне одного.
 *
 * Порожній рядок — планів немає; такий відбиток не записується нікуди
 * (`fingerprint` у схемі має CHECK на непорожнє значення).
 *
 * Розділювачі «=» і «|» безпечні тому, що обидва складники — `uuid` за схемою:
 * жоден із цих символів у них трапитись не може, тож розібрати склеєний рядок
 * інакше, ніж він зібраний, неможливо.
 */
export function planFingerprint(stamps: ReadonlyArray<PlanStamp>): string {
  return [...stamps]
    .sort((a, b) => a.ownerId.localeCompare(b.ownerId))
    .map((stamp) => stamp.ownerId + '=' + stamp.planId)
    .join('|')
}
